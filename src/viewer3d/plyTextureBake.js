const srgbToLinear = (value) => value <= 0.04045
  ? value / 12.92
  : Math.pow((value + 0.055) / 1.055, 2.4);

const linearToSrgbByte = (value) => Math.round(255 * Math.max(0, Math.min(1,
  value <= 0.0031308 ? value * 12.92 : 1.055 * Math.pow(value, 1 / 2.4) - 0.055
)));

export function geometryToBinaryPly(geometry) {
  const position = geometry.getAttribute("position");
  const color = geometry.getAttribute("color");
  const index = geometry.getIndex();
  const faceCount = Math.floor((index?.count ?? position.count) / 3);
  const header = new TextEncoder().encode([
    "ply",
    "format binary_little_endian 1.0",
    "comment Generated by SmartRPD",
    `element vertex ${position.count}`,
    "property float x",
    "property float y",
    "property float z",
    "property uchar red",
    "property uchar green",
    "property uchar blue",
    `element face ${faceCount}`,
    "property list uchar int vertex_indices",
    "end_header",
    "",
  ].join("\n"));
  const output = new Uint8Array(header.length + position.count * 15 + faceCount * 13);
  output.set(header);
  const view = new DataView(output.buffer);
  let offset = header.length;
  for (let i = 0; i < position.count; i += 1) {
    view.setFloat32(offset, position.getX(i), true);
    view.setFloat32(offset + 4, position.getY(i), true);
    view.setFloat32(offset + 8, position.getZ(i), true);
    output[offset + 12] = linearToSrgbByte(color.getX(i));
    output[offset + 13] = linearToSrgbByte(color.getY(i));
    output[offset + 14] = linearToSrgbByte(color.getZ(i));
    offset += 15;
  }
  for (let i = 0; i < faceCount; i += 1) {
    output[offset] = 3;
    for (let corner = 0; corner < 3; corner += 1) {
      const vertex = index ? index.getX(i * 3 + corner) : i * 3 + corner;
      view.setInt32(offset + 1 + corner * 4, vertex, true);
    }
    offset += 13;
  }
  return output;
}

export function applyTextureToGeometry(geometry, pixels, width, height) {
  const uv = geometry.getAttribute("uv");
  if (!uv || uv.count !== geometry.getAttribute("position")?.count) {
    throw new Error("PLY does not contain per-face texture coordinates.");
  }

  const colors = new Float32Array(uv.count * 3);
  for (let i = 0; i < uv.count; i += 1) {
    const x = Math.max(0, Math.min(width - 1, uv.getX(i) * (width - 1)));
    const y = Math.max(0, Math.min(height - 1, (1 - uv.getY(i)) * (height - 1)));
    const x0 = Math.floor(x);
    const y0 = Math.floor(y);
    const x1 = Math.min(x0 + 1, width - 1);
    const y1 = Math.min(y0 + 1, height - 1);
    const tx = x - x0;
    const ty = y - y0;
    for (let channel = 0; channel < 3; channel += 1) {
      const at = (px, py) => pixels[(py * width + px) * 4 + channel];
      const top = at(x0, y0) * (1 - tx) + at(x1, y0) * tx;
      const bottom = at(x0, y1) * (1 - tx) + at(x1, y1) * tx;
      colors[i * 3 + channel] = srgbToLinear((top * (1 - ty) + bottom * ty) / 255);
    }
  }
  geometry.setAttribute("color", new THREE.BufferAttribute(colors, 3));
  return geometry;
}

const textureInfoFromPly = (bytes) => {
  const header = new TextDecoder("ascii").decode(bytes.subarray(0, Math.min(bytes.length, 16384)));
  return {
    name: header.match(/^comment\s+TextureFile\s+(.+)$/mi)?.[1]?.trim() || "",
    is3Shape: /^comment\s+provider\s+3Shape\s*$/mi.test(header),
  };
};

