import { colorAttributeTo3ShapeV } from "./plyTextureBake.js";

const cleanName = (name) => String(name || "mesh").replace(/\.[^.]+$/, "").replace(/[^a-z0-9_-]+/gi, "_");

const transformedPoint = (attribute, index, matrix) => {
  const x = attribute.array[index * attribute.itemSize];
  const y = attribute.array[index * attribute.itemSize + 1];
  const z = attribute.array[index * attribute.itemSize + 2];
  const e = matrix?.elements;
  if (!e) return [x, y, z];
  return [
    e[0] * x + e[4] * y + e[8] * z + e[12],
    e[1] * x + e[5] * y + e[9] * z + e[13],
    e[2] * x + e[6] * y + e[10] * z + e[14],
  ];
};

export function meshGroupToPly(meshes) {
  const usable = (meshes || []).filter((mesh) => mesh?.isMesh && mesh.geometry?.attributes?.position);
  const vertexCount = usable.reduce((sum, mesh) => sum + mesh.geometry.attributes.position.count, 0);
  const faceCount = usable.reduce((sum, mesh) => {
    const geometry = mesh.geometry;
    return sum + Math.floor((geometry.index?.count ?? geometry.attributes.position.count) / 3);
  }, 0);
  const hasColors = usable.some((mesh) => mesh.geometry.attributes.color);
  const lines = [
    "ply",
    "format ascii 1.0",
    "comment Generated by SmartRPD",
    ...(hasColors ? ["comment TextureFile Undercut.jpg", "comment provider 3Shape"] : []),
    `element vertex ${vertexCount}`,
    "property float x",
    "property float y",
    "property float z",
  ];
  lines.push(`element face ${faceCount}`, "property list uchar int vertex_indices");
  if (hasColors) lines.push("property list uchar float texcoord");
  lines.push("end_header");

  usable.forEach((mesh) => {
    mesh.updateWorldMatrix?.(true, false);
    const position = mesh.geometry.attributes.position;
    for (let i = 0; i < position.count; i += 1) {
      const vertex = transformedPoint(position, i, mesh.matrixWorld);
      lines.push(vertex.join(" "));
    }
  });

  let offset = 0;
  usable.forEach((mesh) => {
    const geometry = mesh.geometry;
    const count = geometry.index?.count ?? geometry.attributes.position.count;
    for (let i = 0; i + 2 < count; i += 3) {
      const at = (n) => offset + (geometry.index ? geometry.index.array[i + n] : i + n);
      const face = `3 ${at(0)} ${at(1)} ${at(2)}`;
      const color = geometry.attributes.color;
      const uv = hasColors
        ? ` 6 0 ${colorAttributeTo3ShapeV(color, geometry.index ? geometry.index.array[i] : i)} 0 ${colorAttributeTo3ShapeV(color, geometry.index ? geometry.index.array[i + 1] : i + 1)} 0 ${colorAttributeTo3ShapeV(color, geometry.index ? geometry.index.array[i + 2] : i + 2)}`
        : "";
      lines.push(face + uv);
    }
    offset += geometry.attributes.position.count;
  });
  return new TextEncoder().encode(`${lines.join("\n")}\n`);
}

export function downloadMeshesAsPly(meshes, filename) {
  const blob = new Blob([meshGroupToPly(meshes)], { type: "application/octet-stream" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${cleanName(filename)}.ply`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
